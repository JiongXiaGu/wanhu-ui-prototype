import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import sharp from 'sharp';
import * as lucide from 'lucide-react';
import { ICON_SOURCE_NAMES } from './icon-source-list.mjs';

const ROOT = process.cwd();
const SVG_DIR = path.join(ROOT, 'AssetsSource/UI/Icons/svg');
const PNG_DIR = path.join(ROOT, 'public/assets/ui/icons');
const TS_DIR = path.join(ROOT, 'src/ui/icons');
const LICENSE_OUT = path.join(ROOT, 'AssetsSource/UI/Icons/LUCIDE_LICENSE.txt');
const MANIFEST_PATH = path.join(PNG_DIR, 'icon-manifest.json');
const GENERATED_TS_PATH = path.join(TS_DIR, 'icon-manifest.generated.ts');
const RUNTIME_TS_PATH = path.join(TS_DIR, 'runtime-icons.generated.tsx');

const CANVAS_SIZE = 64;
const STROKE_WIDTH = 1.7;
const SOURCE_PACKAGE = 'lucide-react';
const SOURCE_VERSION = '1.47.0';

function toAssetId(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])(\d)/g, '$1-$2')
    .replace(/(\d)([A-Za-z])/g, '$1-$2')
    .toLowerCase();
}

async function cleanOutput() {
  await rm(SVG_DIR, { recursive: true, force: true });
  await rm(PNG_DIR, { recursive: true, force: true });
  await mkdir(SVG_DIR, { recursive: true });
  await mkdir(PNG_DIR, { recursive: true });
  await mkdir(TS_DIR, { recursive: true });
}

function renderSourceSvg(sourceName) {
  const Icon = lucide[sourceName];
  if (!Icon) throw new Error('lucide-react does not export "' + sourceName + '"');

  const markup = renderToStaticMarkup(
    createElement(Icon, {
      width: CANVAS_SIZE,
      height: CANVAS_SIZE,
      size: CANVAS_SIZE,
      color: '#ffffff',
      strokeWidth: STROKE_WIDTH,
      'aria-hidden': 'true',
    }),
  );

  return markup
    .replaceAll('currentColor', '#ffffff')
    .replace(/ class="[^"]*"/g, '')
    .replace(/ aria-hidden="true"/g, '');
}

function buildGeneratedTs(entries) {
  const assetLines = entries
    .map((entry) => "  '" + entry.id + "': '" + entry.runtimePath + "',")
    .join('\n');
  const sourceLines = entries
    .map((entry) => "  '" + entry.id + "': '" + entry.sourceName + "',")
    .join('\n');

  return [
    '/* AUTO-GENERATED by scripts/icons/build-icon-assets.mjs. Do not edit manually. */',
    'export const UI_ICON_ASSETS = {',
    assetLines,
    '} as const;',
    '',
    'export type UiIconId = keyof typeof UI_ICON_ASSETS;',
    '',
    'export const UI_ICON_SOURCE_NAMES: Record<UiIconId, string> = {',
    sourceLines,
    '};',
    '',
  ].join('\n');
}

function buildRuntimeIconTs(entries) {
  const iconLines = entries
    .map((entry) => 'export const ' + entry.sourceName + ": UiIconComponent = createUiIconComponent('" + entry.id + "');")
    .join('\n');

  return [
    '/* AUTO-GENERATED by scripts/icons/build-icon-assets.mjs. Do not edit manually. */',
    "import { createUiIconComponent } from './UiIcon';",
    "import type { UiIconComponent } from './icon-types';",
    '',
    "export type { UiIconComponent as LucideIcon } from './icon-types';",
    '',
    iconLines,
    '',
  ].join('\n');
}

async function copyLicense() {
  const candidates = [
    path.join(ROOT, 'node_modules/lucide-react/LICENSE'),
    path.join(ROOT, 'node_modules/lucide-react/LICENSE.md'),
  ];

  for (const candidate of candidates) {
    try {
      const text = await readFile(candidate, 'utf8');
      await mkdir(path.dirname(LICENSE_OUT), { recursive: true });
      await writeFile(
        LICENSE_OUT,
        'Generated icon assets originate from ' + SOURCE_PACKAGE + '@' + SOURCE_VERSION + '.\n\n' + text,
        'utf8',
      );
      return;
    } catch {
      // Try next package license path.
    }
  }

  throw new Error('Unable to locate lucide-react license file.');
}

await cleanOutput();

const seenIds = new Set();
const entries = [];

for (const sourceName of ICON_SOURCE_NAMES) {
  const id = toAssetId(sourceName);
  if (seenIds.has(id)) throw new Error('Duplicate icon asset id: ' + id);
  seenIds.add(id);

  const svg = renderSourceSvg(sourceName);
  const svgPath = path.join(SVG_DIR, id + '.svg');
  const pngPath = path.join(PNG_DIR, id + '.png');

  await writeFile(svgPath, svg + '\n', 'utf8');
  await sharp(Buffer.from(svg))
    .png({ compressionLevel: 9, palette: false })
    .toFile(pngPath);

  const meta = await sharp(pngPath).metadata();
  if (meta.width !== CANVAS_SIZE || meta.height !== CANVAS_SIZE || !meta.hasAlpha) {
    throw new Error(
      id + '.png failed runtime contract: ' + meta.width + 'x' + meta.height + ', alpha=' + meta.hasAlpha,
    );
  }

  entries.push({
    id,
    sourceName,
    sourceSvg: 'AssetsSource/UI/Icons/svg/' + id + '.svg',
    runtimePath: '/assets/ui/icons/' + id + '.png',
    png: 'public/assets/ui/icons/' + id + '.png',
  });
}

entries.sort((a, b) => a.id.localeCompare(b.id));

const manifest = {
  schemaVersion: 1,
  canvasSize: CANVAS_SIZE,
  strokeWidth: STROKE_WIDTH,
  sourcePackage: {
    name: SOURCE_PACKAGE,
    version: SOURCE_VERSION,
  },
  runtime: {
    format: 'png',
    color: '#ffffff',
    background: 'transparent',
    web: 'alpha-mask-currentColor',
    unity: 'sprite-tint',
  },
  iconCount: entries.length,
  icons: entries,
};

await writeFile(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
await writeFile(GENERATED_TS_PATH, buildGeneratedTs(entries), 'utf8');
await writeFile(RUNTIME_TS_PATH, buildRuntimeIconTs(entries), 'utf8');
await copyLicense();

console.log(
  'Generated ' + entries.length + ' UI icons: SVG Source + ' + CANVAS_SIZE + 'x' + CANVAS_SIZE +
  ' PNG Runtime (stroke ' + STROKE_WIDTH + ').',
);
