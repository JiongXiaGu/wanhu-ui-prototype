import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import sharp from 'sharp';
import * as lucide from 'lucide-react';
import { ICON_SOURCE_NAMES } from './icon-source-list.mjs';
import { CUSTOM_ICON_PATHS, renderCustomIcon } from './custom-icon-sources.mjs';

const ROOT = process.cwd();
const SVG_DIR = path.join(ROOT, 'AssetsSource/UI/Icons/svg');
const PNG_DIR = path.join(ROOT, 'public/assets/ui/icons');
const TS_DIR = path.join(ROOT, 'src/ui/icons');
const LICENSE_OUT = path.join(ROOT, 'AssetsSource/UI/Icons/LUCIDE_LICENSE.txt');
const CANVAS_SIZE = 64;
const STROKE_WIDTH = 1.7;
const SOURCE_PACKAGE = 'lucide-react';
const SOURCE_VERSION = '1.47.0';
function toAssetId(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Za-z])(\d)/g, '$1-$2').replace(/(\d)([A-Za-z])/g, '$1-$2').toLowerCase();
}
function renderSourceSvg(sourceName) {
  if (Object.hasOwn(CUSTOM_ICON_PATHS, sourceName)) return renderCustomIcon(sourceName, CANVAS_SIZE, STROKE_WIDTH);
  const Icon = lucide[sourceName];
  if (!Icon) throw new Error('lucide-react does not export "' + sourceName + '"');
  return renderToStaticMarkup(createElement(Icon, { width: CANVAS_SIZE, height: CANVAS_SIZE, size: CANVAS_SIZE, color: '#ffffff', strokeWidth: STROKE_WIDTH, 'aria-hidden': 'true' }))
    .replaceAll('currentColor', '#ffffff').replace(/ class="[^"]*"/g, '').replace(/ aria-hidden="true"/g, '');
}
function buildGeneratedTs(entries) {
  return [
    '/* AUTO-GENERATED by scripts/icons/build-icon-assets.mjs. Do not edit manually. */',
    'export const UI_ICON_ASSETS = {',
    ...entries.map(entry => `  '${entry.id}': '${entry.runtimePath}',`),
    '} as const;', '', 'export type UiIconId = keyof typeof UI_ICON_ASSETS;', '',
    'export const UI_ICON_SOURCE_NAMES: Record<UiIconId, string> = {',
    ...entries.map(entry => `  '${entry.id}': '${entry.sourceName}',`),
    '};', '',
  ].join('\n');
}
function buildRuntimeIconTs(entries) {
  return [
    '/* AUTO-GENERATED by scripts/icons/build-icon-assets.mjs. Do not edit manually. */',
    "import { createUiIconComponent } from './UiIcon';", "import type { UiIconComponent } from './icon-types';", '',
    "export type { UiIconComponent } from './icon-types';", '',
    ...entries.map(entry => `export const ${entry.sourceName}: UiIconComponent = createUiIconComponent('${entry.id}');`), '',
  ].join('\n');
}
async function copyLicense() {
  for (const filename of ['LICENSE', 'LICENSE.md']) {
    try {
      const text = await readFile(path.join(ROOT, 'node_modules/lucide-react', filename), 'utf8');
      await writeFile(LICENSE_OUT, 'Generated icon assets originate from ' + SOURCE_PACKAGE + '@' + SOURCE_VERSION + '.\n\n' + text, 'utf8');
      return;
    } catch { /* 尝试下一个许可文件路径。 */ }
  }
  throw new Error('Unable to locate lucide-react license file.');
}

// 先校验和渲染全部来源，避免非法来源在清理输出后才报错。
const seen = new Set();
const sources = ICON_SOURCE_NAMES.map(sourceName => {
  const id = toAssetId(sourceName);
  if (seen.has(id)) throw new Error('Duplicate icon asset id: ' + id);
  seen.add(id);
  return { id, sourceName, svg: renderSourceSvg(sourceName) };
});
for (const dir of [SVG_DIR, PNG_DIR]) { await rm(dir, { recursive: true, force: true }); await mkdir(dir, { recursive: true }); }
await mkdir(TS_DIR, { recursive: true });
const entries = [];
for (const { id, sourceName, svg } of sources) {
  await writeFile(path.join(SVG_DIR, id + '.svg'), svg + '\n', 'utf8');
  const pngPath = path.join(PNG_DIR, id + '.png');
  await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: false }).toFile(pngPath);
  const meta = await sharp(pngPath).metadata();
  if (meta.width !== CANVAS_SIZE || meta.height !== CANVAS_SIZE || !meta.hasAlpha) throw new Error(id + ' violates the PNG runtime contract.');
  entries.push({ id, sourceName, sourceSvg: 'AssetsSource/UI/Icons/svg/' + id + '.svg', runtimePath: '/assets/ui/icons/' + id + '.png', png: 'public/assets/ui/icons/' + id + '.png', ...(Object.hasOwn(CUSTOM_ICON_PATHS, sourceName) ? { origin: 'wanhu-authored' } : {}) });
}
entries.sort((a, b) => a.id.localeCompare(b.id));
const manifest = {
  schemaVersion: 1, canvasSize: CANVAS_SIZE, strokeWidth: STROKE_WIDTH,
  // 兼容原有通用图标来源字段，自定义条目以 origin 显式区分，不冒用第三方来源。
  sourcePackage: { name: SOURCE_PACKAGE, version: SOURCE_VERSION },
  customSource: 'scripts/icons/custom-icon-sources.mjs',
  runtime: { format: 'png', color: '#ffffff', background: 'transparent', web: 'alpha-mask-currentColor', unity: 'sprite-tint' },
  iconCount: entries.length, icons: entries,
};
await writeFile(path.join(PNG_DIR, 'icon-manifest.json'), JSON.stringify(manifest) + '\n', 'utf8');
await writeFile(path.join(TS_DIR, 'icon-manifest.generated.ts'), buildGeneratedTs(entries), 'utf8');
await writeFile(path.join(TS_DIR, 'runtime-icons.generated.tsx'), buildRuntimeIconTs(entries), 'utf8');
await copyLicense();
console.log(`Generated ${entries.length} SVG Source + 64×64 PNG Runtime icons (stroke ${STROKE_WIDTH}).`);
